import { createHash } from 'node:crypto';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

function walk(dir, root, acc = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, root, acc);
    else acc.push(`/${relative(root, path).split('\\').join('/')}`);
  }
  return acc;
}

const files = walk('dist', 'dist')
  .filter((file) => file !== '/sw.js')
  .sort();
const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
const source = `/* Generated by scripts/write-sw.mjs. Cache id ${version}. */
const CACHE = 'signbridge-${version}';
const PRECACHE = ${JSON.stringify(files, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() => (event.request.mode === 'navigate' ? caches.match('/index.html') : Promise.reject()));
    }),
  );
});
`;

writeFileSync('dist/sw.js', source);
console.log(`wrote dist/sw.js with ${files.length} precached files (${version})`);
